  status         text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  note           text check (note is null or char_length(note) <= 500),
  decided_by     uuid references auth.users(id),
  decided_at     timestamptz,
  created_at     timestamptz not null default now()
);
create unique index if not exists claims_one_pending on public.claims (business_id, user_id) where status = 'pending';
alter table public.claims enable row level security;

create or replace function public.claims_before_insert() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  new.user_id := auth.uid(); new.status := 'pending'; new.note := null; new.decided_by := null; new.decided_at := null; new.created_at := now();
  if new.user_id is null then raise exception 'سجّل الدخول أولاً'; end if;
  if new.proof_path is not null and new.proof_path !~ ('^' || new.user_id::text || '/') then raise exception 'مسار صورة غير صالح'; end if;
  if not exists (select 1 from posts p where p.id = new.business_id and p.type = 'business'
       and ((p.status = 'pending' and p.author_id = new.user_id and p.owner_id is null) or (p.status = 'published' and p.owner_id is distinct from new.user_id))) then
    raise exception 'لا يمكن طلب ملكية هذا النشاط'; end if;
  if (select count(*) from claims where user_id = new.user_id and status = 'pending') >= 3 then
    raise exception 'عندك ٣ طلبات قيد التحقق'; end if;
  return new;
end $$;
drop trigger if exists claims_before_insert on public.claims;
create trigger claims_before_insert before insert on public.claims for each row execute function public.claims_before_insert();

drop policy if exists claims_insert on public.claims;
create policy claims_insert on public.claims for insert to authenticated with check (user_id = auth.uid());
drop policy if exists claims_read on public.claims;
create policy claims_read on public.claims for select using (user_id = auth.uid() or public.is_admin());

