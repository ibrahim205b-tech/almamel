create or replace function public.moderate_post(p_id bigint, p_action text, p_reason text default null) returns void
language plpgsql security definer set search_path = public as $$
declare p posts; days int;
begin
  if not public.is_admin() then raise exception 'غير مسموح'; end if;
  select * into p from posts where id = p_id for update;
  if not found then raise exception 'المنشور غير موجود'; end if;
  if p_action in ('reject', 'hide', 'remove') and char_length(trim(coalesce(p_reason, ''))) < 3 then raise exception 'اكتب السبب'; end if;
  if p_action = 'approve' then
    if p.status not in ('pending', 'hidden') then raise exception 'لا يمكن نشر منشور بهذه الحالة'; end if;
    days := case p.type when 'job' then 30 when 'property' then 60 when 'market' then 30 when 'offer' then 14
                        when 'community' then 30 when 'help' then 30 when 'service' then 365 else null end;
    update posts set status = 'published', status_reason = null, approved_by = auth.uid(),
      published_at = coalesce(case when p.status = 'hidden' then p.published_at end, now()),
      expires_at = case when p.status = 'hidden' then p.expires_at when days is null then null else now() + make_interval(days => days) end
      where id = p_id;
  elsif p_action = 'reject' then
    if p.status <> 'pending' then raise exception 'المنشور ليس بانتظار المراجعة'; end if;
    update posts set status = 'rejected', status_reason = p_reason where id = p_id;
  elsif p_action = 'hide' then
    if p.status <> 'published' then raise exception 'المنشور غير منشور'; end if;
    update posts set status = 'hidden', status_reason = p_reason where id = p_id;
  elsif p_action = 'remove' then
    update posts set status = 'removed', status_reason = p_reason where id = p_id;
  elsif p_action in ('verify', 'unverify') then
    update posts set verified = (p_action = 'verify') where id = p_id and type in ('business', 'help');
  elsif p_action in ('official', 'unofficial') then
    update posts set is_official = (p_action = 'official') where id = p_id and type = 'community';
  else raise exception 'إجراء غير معروف'; end if;
  insert into moderation_log (post_id, actor_id, action, reason) values (p_id, auth.uid(), p_action, p_reason);
end $$;

create or replace function public.decide_claim(p_id bigint, p_approve boolean, p_note text default null) returns void
language plpgsql security definer set search_path = public as $$
declare c claims; p posts;
begin
  if not public.is_admin() then raise exception 'غير مسموح'; end if;
  select * into c from claims where id = p_id and status = 'pending' for update;
  if not found then raise exception 'الطلب غير موجود أو تمت مراجعته'; end if;
  select * into p from posts where id = c.business_id for update;
  update claims set status = case when p_approve then 'approved' else 'rejected' end, note = p_note, decided_by = auth.uid(), decided_at = now() where id = p_id;
  if p_approve then
    update posts set owner_id = c.user_id where id = p.id;
    update claims set status = 'rejected', note = 'تم اعتماد مالك آخر', decided_by = auth.uid(), decided_at = now()
      where business_id = p.id and status = 'pending' and id <> p_id;
    if p.status = 'pending' then
      update posts set status = 'published', approved_by = auth.uid(), published_at = now(), status_reason = null where id = p.id;
    end if;
  elsif p.status = 'pending' and p.author_id = c.user_id then
    update posts set status = 'rejected', status_reason = coalesce(nullif(trim(p_note), ''), 'لم نتمكن من التحقق من ملكية النشاط') where id = p.id;
  end if;
  insert into moderation_log (post_id, actor_id, action, reason) values (p.id, auth.uid(), case when p_approve then 'claim_approve' else 'claim_reject' end, p_note);
end $$;

-- المدير: تمييز منشور مدفوع (يظهر أولاً) لعدد أيام، أو إلغاء التمييز بـ 0
create or replace function public.feature_post(p_id bigint, p_days integer default null) returns void
language plpgsql security definer set search_path = public as $$
declare d int := coalesce(p_days, public.feature_days());
begin
  if not public.is_admin() then raise exception 'غير مسموح'; end if;
  if d < 0 or d > 365 then raise exception 'عدد أيام غير صالح'; end if;
  update posts set featured_until = case when d = 0 then null
      else greatest(coalesce(featured_until, now()), now()) + make_interval(days => d) end
    where id = p_id and status = 'published';
  if not found then raise exception 'المنشور غير منشور'; end if;
  insert into moderation_log (post_id, actor_id, action, reason) values (p_id, auth.uid(), 'feature', d::text || ' days');
end $$;

-- المدير: تأكيد استلام رسوم الإعلان (يمسح المبلغ المستحق)
create or replace function public.mark_fee_paid(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'غير مسموح'; end if;
  update posts set fee_due = 0 where id = p_id;
  if not found then raise exception 'المنشور غير موجود'; end if;
  insert into moderation_log (post_id, actor_id, action) values (p_id, auth.uid(), 'fee_paid');
end $$;

-- صاحب المحل: شعار المحل (يظهر مباشرة بجانب الاسم بعد التحديث التلقائي)
create or replace function public.set_business_logo(p_id bigint, p_path text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if p_path is not null and not valid_media_path(p_path, auth.uid()) then raise exception 'مسار صورة غير صالح'; end if;
  update posts set logo = p_path where id = p_id and type = 'business' and owner_id = auth.uid();
  if not found then raise exception 'غير مسموح'; end if;
end $$;

-- صاحب المحل: حالة المحل الآن
create or replace function public.set_open_state(p_id bigint, p_state text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if p_state not in ('open', 'closed', 'unknown') then raise exception 'حالة غير صالحة'; end if;
  update posts set open_state = p_state where id = p_id and type = 'business' and owner_id = auth.uid();
  if not found then raise exception 'غير مسموح'; end if;
end $$;

-- صاحب المحل: تعديل المعلومات يعيد المحل للمراجعة (لا يُنشر تعديل من دون موافقة)
create or replace function public.update_business(p_id bigint, p_title text, p_body text, p_area text, p_phone text, p_whatsapp boolean, p_details jsonb, p_images text[])
returns void language plpgsql security definer set search_path = public as $$
declare img text;
begin
  if not exists (select 1 from posts where id = p_id and type = 'business' and owner_id = auth.uid() and status in ('published', 'pending', 'hidden')) then
    raise exception 'غير مسموح'; end if;
  foreach img in array coalesce(p_images, '{}') loop
