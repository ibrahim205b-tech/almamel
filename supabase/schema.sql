create table if not exists public.posts (
  id            bigint generated by default as identity (start with 1000000) primary key,
  type          text not null check (type in ('business', 'job', 'property', 'service', 'market', 'offer', 'community', 'help')),
  title         text not null check (char_length(title) between 3 and 100),
  body          text not null default '' check (char_length(body) <= 4000),
  category      text not null check (char_length(category) between 2 and 60),
  area          text not null default 'المعامل' check (char_length(area) between 2 and 60),
  price         bigint check (price is null or price between 0 and 100000000000),
  contact_phone text check (contact_phone is null or contact_phone ~ '^07[0-9]{9}$'),
  show_phone    boolean not null default true,
  whatsapp      boolean not null default false,
  details       jsonb not null default '{}'::jsonb check (jsonb_typeof(details) = 'object' and octet_length(details::text) <= 6000),
  images        text[] not null default '{}' check (cardinality(images) <= 6),
  guest_name    text check (guest_name is null or char_length(guest_name) between 2 and 60),
  author_id     uuid references auth.users(id) on delete set null,
  owner_id      uuid references auth.users(id) on delete set null,
  business_id   bigint references public.posts(id) on delete set null,
  status        text not null default 'pending' check (status in ('pending', 'published', 'rejected', 'hidden', 'removed')),
  status_reason text check (status_reason is null or char_length(status_reason) <= 500),
  open_state    text not null default 'unknown' check (open_state in ('open', 'closed', 'unknown')),
  verified      boolean not null default false,
  is_official   boolean not null default false,
  approved_by   uuid references auth.users(id),
  published_at  timestamptz,
  expires_at    timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists posts_public on public.posts (status, type, published_at desc);
create index if not exists posts_author on public.posts (author_id, created_at);
create index if not exists posts_owner on public.posts (owner_id);
create index if not exists posts_guest on public.posts (created_at) where author_id is null;
-- رسوم الإعلان: الأول مجاني، وما بعده بسعر ثابت تتحقق منه الإدارة قبل النشر.
alter table public.posts add column if not exists fee_due integer not null default 0 check (fee_due >= 0);
