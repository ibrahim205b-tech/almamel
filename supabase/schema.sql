-- يدير القائمة: المالك المعتمد، أو صاحب الطلب أثناء التحقق، أو المدير.
create or replace function public.can_manage(bid bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select public.is_admin() or exists (
    select 1 from posts p where p.id = bid and p.type = 'business' and p.status not in ('removed', 'rejected')
      and (p.owner_id = auth.uid() or (p.owner_id is null and p.author_id = auth.uid())));
$$;

create or replace function public.is_public_business(bid bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from posts p where p.id = bid and p.type = 'business' and p.status = 'published');
$$;

create or replace function public.menu_items_guard() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'UPDATE' then new.business_id := old.business_id; end if;
  -- الصورة تُفحص فقط إذا تغيّرت (حتى صاحب المحل يكدر يعدّل صنف صورته رفعتها الإدارة)
  if new.image is not null and (tg_op = 'INSERT' or new.image is distinct from old.image)
     and new.image !~ ('^u/' || auth.uid()::text || '/') and not public.is_admin() then
    raise exception 'مسار صورة غير صالح'; end if;
  if tg_op = 'INSERT' and (select count(*) from menu_items where business_id = new.business_id) >= 300 then
    raise exception 'الحد الأقصى ٣٠٠ صنف'; end if;
  new.updated_at := now();
  return new;
end $$;
drop trigger if exists menu_items_guard on public.menu_items;
create trigger menu_items_guard before insert or update on public.menu_items for each row execute function public.menu_items_guard();

drop policy if exists menu_read on public.menu_items;
create policy menu_read on public.menu_items for select using (public.is_public_business(business_id) or public.can_manage(business_id));
drop policy if exists menu_write on public.menu_items;
create policy menu_write on public.menu_items for insert to authenticated with check (public.can_manage(business_id));
drop policy if exists menu_update on public.menu_items;
create policy menu_update on public.menu_items for update to authenticated using (public.can_manage(business_id)) with check (public.can_manage(business_id));
drop policy if exists menu_delete on public.menu_items;
create policy menu_delete on public.menu_items for delete to authenticated using (public.can_manage(business_id));

