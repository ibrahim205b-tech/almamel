  id             bigint generated by default as identity primary key,
  business_id    bigint not null references public.posts(id) on delete cascade,
  user_id        uuid not null default auth.uid() references auth.users(id) on delete cascade,
  message        text not null check (char_length(message) between 10 and 1000),
  business_phone text check (business_phone is null or business_phone ~ '^07[0-9]{9}$'),
  proof_path     text check (proof_path is null or proof_path ~ '^[0-9a-f-]{36}/[0-9a-f]{32}\.webp$'),
  status         text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  note           text check (note is null or char_length(note) <= 500),
