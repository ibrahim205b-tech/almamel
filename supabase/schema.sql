-- ---------- الملفات الشخصية والأدوار ----------

create table if not exists public.profiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  name       text not null check (char_length(name) between 2 and 60),
  phone      text not null check (phone ~ '^07[0-9]{9}$'),
  role       text not null default 'owner' check (role in ('owner', 'admin')),
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;

-- الدور لا يُقرأ من المتصفح أبداً: كل حساب جديد «صاحب محل»، والمدير يُعيَّن من SQL فقط.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  v_name  text := trim(coalesce(new.raw_user_meta_data->>'name', ''));
  v_phone text := coalesce(new.raw_user_meta_data->>'phone', '');
begin
  if char_length(v_name) not between 2 and 60 then v_name := 'صاحب محل'; end if;
  if v_phone !~ '^07[0-9]{9}$' then v_phone := '07000000000'; end if;
  insert into public.profiles (id, name, phone) values (new.id, v_name, v_phone) on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

drop policy if exists profiles_read on public.profiles;
create policy profiles_read on public.profiles for select using (id = auth.uid() or public.is_admin());
-- لا توجد سياسة تعديل: لا أحد يغيّر دوره من المتصفح.

