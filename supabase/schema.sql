create or replace function public.valid_media_path(p text, uid uuid) returns boolean
language sql immutable as $$
  select case when uid is null then p ~ '^guest/[0-9a-f]{32}\.webp$'
              else p ~ ('^u/' || uid::text || '/[0-9a-f]{32}\.webp$') end;
$$;

-- كل منشور جديد يدخل «بانتظار المراجعة» مهما أرسل المتصفح. الحقول الحساسة تُفرض هنا.
create or replace function public.posts_before_insert() returns trigger
language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); p text;
begin
  new.status := 'pending'; new.status_reason := null; new.approved_by := null;
  new.published_at := null; new.expires_at := null; new.verified := false; new.is_official := false;
  new.owner_id := null; new.open_state := 'unknown'; new.featured_until := null;
  -- الشعار: للمحلات فقط ومن مجلد صاحب الحساب نفسه
  if new.logo is not null and (uid is null or new.type <> 'business' or not valid_media_path(new.logo, uid)) then new.logo := null; end if;
  new.author_id := uid; new.created_at := now(); new.updated_at := now();
  -- الإعلان الأول لكل حساب (أو رقم هاتف للزوار) مجاني، وكل إعلان بعده برسوم ثابتة.
  -- طلب تسجيل المحل نفسه لا يُحسب ولا يُدفع عليه.
  new.fee_due := 0;
  if new.type <> 'business' and exists (
      select 1 from posts q where q.type <> 'business' and q.status <> 'rejected'
        and ((uid is not null and q.author_id = uid) or (new.contact_phone is not null and q.contact_phone = new.contact_phone))) then
    new.fee_due := public.ad_fee();
  end if;
  if uid is null then
    if new.type = 'business' then raise exception 'المحلات تُضاف من حساب صاحب المحل'; end if;
    if new.guest_name is null or new.contact_phone is null then raise exception 'الاسم ورقم التواصل مطلوبان'; end if;
    if cardinality(new.images) > 3 then raise exception 'الحد الأقصى ٣ صور'; end if;
    if (select count(*) from posts where author_id is null and created_at > now() - interval '1 hour') >= 30 then
      raise exception 'وصلت إعلانات كثيرة الآن. حاول بعد ساعة.'; end if;
  else
    new.guest_name := null;
    if (select count(*) from posts where author_id = uid and created_at > now() - interval '1 day') >= 15 then
      raise exception 'وصلت للحد اليومي للمنشورات.'; end if;
  end if;
  foreach p in array new.images loop
    if not valid_media_path(p, uid) then raise exception 'مسار صورة غير صالح'; end if;
  end loop;
  if new.business_id is not null and not exists (
      select 1 from posts b where b.id = new.business_id and b.type = 'business' and b.status = 'published' and b.owner_id = uid) then
    new.business_id := null;
  end if;
  if new.type = 'help' and coalesce((new.details->>'consent')::boolean, false) is not true then
    raise exception 'يجب تأكيد موافقة صاحب الحالة على النشر'; end if;
  return new;
end $$;

drop trigger if exists posts_before_insert on public.posts;
create trigger posts_before_insert before insert on public.posts for each row execute function public.posts_before_insert();

-- أي تعديل مباشر (حتى من دالة) يحدّث وقت التعديل؛ وتغيير الحالة إلى «منشور» يتطلب موافقة مدير.
create or replace function public.posts_before_update() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  if new.status = 'published' and old.status <> 'published' and (new.approved_by is null or new.published_at is null) then
    raise exception 'النشر يتطلب موافقة الإدارة';
  end if;
  return new;
end $$;
drop trigger if exists posts_before_update on public.posts;
create trigger posts_before_update before update on public.posts for each row execute function public.posts_before_update();

-- الجدول نفسه لا يقرؤه إلا صاحب المنشور والمدير. العامة تقرأ من public_posts أدناه
-- (المنشور فقط، ومن دون اسم المرسل أو الرقم المخفي).
drop policy if exists posts_read on public.posts;
create policy posts_read on public.posts for select using (
  author_id = auth.uid() or owner_id = auth.uid() or public.is_admin()
);

create or replace view public.public_posts with (security_barrier = true) as
  select id, type, title, body, category, area, price,
         case when show_phone then contact_phone end as contact_phone, show_phone, whatsapp and show_phone as whatsapp,
         details, images, business_id, open_state, verified, is_official, published_at, expires_at, updated_at,
         case when featured_until > now() then featured_until end as featured_until, logo
  from public.posts
  where status = 'published' and (expires_at is null or expires_at > now());
grant select on public.public_posts to anon, authenticated;
